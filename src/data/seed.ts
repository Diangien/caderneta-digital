function occurrence(
  id: string,
  studentId: string,
  date: string,
  type: Occurrence['type'],
  description: string,
  measure: string,
  recordedBy: string,
): Occurrence {
  const ts = `${date}T10:00:00.000Z`;
  return { id, studentId, date, type, description, measure, recordedBy, createdAt: ts, updatedAt: ts };
}

